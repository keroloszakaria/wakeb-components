import { test, expect } from '@playwright/test'

test('all 21 gallery examples render, respond and remount with language/theme controls', async ({ page }, info) => {
  const { locale, mode } = info.project.metadata
  const ar = locale === 'ar'
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (['warning', 'error'].includes(message.type())) errors.push(message.text()) })
  await page.goto(`/?lang=${locale}&theme=${mode}`)
  const cards = page.locator('[data-component]')
  await expect(cards).toHaveCount(21)
  await expect(page.locator('html')).toHaveAttribute('dir', ar ? 'rtl' : 'ltr')
  await expect(page.locator('body')).toHaveAttribute('data-mode', String(mode))
  await expect(page.getByTestId('diagnostics')).toHaveText(/: 0$/)
  await page.screenshot({ path: info.outputPath('gallery.png'), fullPage: true })
  await page.screenshot({ path: info.outputPath('gallery-viewport.png') })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true)
  await page.screenshot({ path: info.outputPath('gallery-small.png'), fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  const card = (name: string) => page.locator(`[data-component="${name}"]`)
  await card('WButton').getByRole('button', { name: ar ? 'زر أساسي' : 'Primary action', exact: true }).click()
  await expect(card('WButton').locator('output')).toHaveText(/: 1$/)
  await card('WButton').getByLabel(ar ? 'تحميل' : 'Loading', { exact: true }).check()
  await expect(card('WButton').getByRole('button', { name: ar ? 'زر أساسي' : 'Primary action', exact: true })).toHaveAttribute('aria-busy', 'true')
  await card('WButton').getByLabel(ar ? 'تحميل' : 'Loading', { exact: true }).uncheck()
  await card('WSegmentedProgress').getByRole('slider').press('End')
  await expect(card('WSemiCircleGauge').locator('svg')).toHaveAttribute('aria-label', '100%')
  await card('WAccordion').getByRole('button', { name: ar ? 'تفاصيل الطلب' : 'Request details', exact: true }).click()
  await expect(card('WAccordion').getByRole('textbox')).toBeVisible()
  await card('WTabs').getByRole('tab', { name: ar ? 'النشاط' : 'Activity', exact: true }).click()
  await expect(card('WTabs').getByRole('tabpanel', { name: ar ? 'النشاط' : 'Activity', exact: true })).toContainText(ar ? 'لا يوجد نشاط جديد.' : 'No new activity.')
  await card('WDropdown').getByRole('button', { name: ar ? 'الإجراءات' : 'Actions', exact: true }).click()
  await page.getByRole('menuitem', { name: ar ? 'عرض' : 'View', exact: true }).click()
  await expect(page.getByTestId('events')).toContainText('dropdown.modelValue: view')
  await card('WModal').getByRole('button', { name: ar ? 'فتح الحوار' : 'Open modal', exact: true }).click()
  const modal = page.getByRole('dialog', { name: ar ? 'حوار تجريبي' : 'Demo modal', exact: true })
  await expect(modal).toBeVisible()
  await modal.getByRole('textbox').fill('Gallery smoke')
  await modal.getByRole('button', { name: ar ? 'إلغاء' : 'Cancel', exact: true }).click()
  await expect(modal).toBeHidden()
  await card('WDrawer').getByRole('button', { name: ar ? 'فتح اللوحة' : 'Open drawer', exact: true }).click()
  const drawer = page.getByRole('dialog', { name: ar ? 'لوحة تجريبية' : 'Demo drawer', exact: true })
  await expect(drawer).toBeVisible()
  await drawer.getByRole('button', { name: ar ? 'حوار داخل اللوحة' : 'Nested modal', exact: true }).click()
  const nested = page.getByRole('dialog', { name: ar ? 'حوار داخلي' : 'Nested dialog', exact: true })
  await expect(nested).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(nested).toBeHidden()
  await expect(drawer).toBeVisible()
  await page.keyboard.press('Escape')
  if (info.project.metadata.provider === 'vuetify') {
    await expect(drawer).toHaveAttribute('inert', '')
    await expect(drawer).not.toBeInViewport()
  } else await expect(drawer).toBeHidden()
  await page.locator('#language').click()
  await expect(page.locator('html')).toHaveAttribute('lang', ar ? 'en' : 'ar')
  await expect(cards).toHaveCount(21)
  await page.locator('#theme').click()
  await expect(page.locator('body')).toHaveAttribute('data-mode', mode === 'light' ? 'dark' : 'light')
  await expect(page.getByTestId('diagnostics')).toHaveText(/: 0$/)
  await page.locator('#reset').click()
  await expect(card('WButton').locator('output')).toHaveText(/: 0$/)
  await page.screenshot({ path: info.outputPath('gallery-switched.png'), fullPage: true })
  expect(errors).toEqual([])
})

import assert from "node:assert/strict";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/*
 * Supported peer version matrix (SPEC R10, R22). Each cell is a committed manifest + lockfile under
 * tests/fixtures/peers/<provider>-<tier>. `min` pins the lowest version of every advertised range;
 * `current` uses the ranges themselves, so its lockfile records the newest in-range versions at lock
 * time. check-peers.mjs installs each cell with `npm ci` and writes results.json plus the docs tables;
 * docs-build.mjs calls assertMatrixInSync() offline so manifests, locks, results and docs cannot drift.
 */
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const FIXTURES = join(root, "tests/fixtures/peers");
export const RESULTS = join(FIXTURES, "results.json");
export const TARBALL = "wakeb-components.tgz";
export const PROVIDER_PEERS = { vuetify: ["vuetify"], primevue: ["primevue", "@primeuix/themes"], shadcn: ["reka-ui"] };
export const TIERS = ["min", "current"];
export const COLUMNS = ["vue", "vite", "vuetify", "primevue", "@primeuix/themes", "reka-ui"];
export const CELLS = Object.keys(PROVIDER_PEERS).flatMap((framework) => TIERS.map((tier) => ({ id: `${framework}-${tier}`, framework, tier })));
export const DOCS = { en: join(root, "docs/guide/installation.md"), ar: join(root, "docs/ar/guide/installation.md") };
const START = "<!-- peer-matrix:start (generated by npm run check:peers) -->";
const END = "<!-- peer-matrix:end -->";

export const readPackage = () => JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const readJson = (path) => JSON.parse(readFileSync(path, "utf8"));

/** Lowest version of a simple advertised range (`^x.y.z`, `~x.y.z`, `>=x.y.z`). */
export function minVersion(range) {
  const match = /^(?:\^|~|>=)?(\d+\.\d+\.\d+)$/.exec(range.trim());
  assert(match, `Unsupported peer range ${range}; use ^x.y.z`);
  return match[1];
}

/** The manifest a cell must have for the current package.json peer ranges. */
export function expectedManifest(cell, pkg = readPackage()) {
  const pick = (name) => (cell.tier === "min" ? minVersion(pkg.peerDependencies[name]) : pkg.peerDependencies[name]);
  const dependencies = { "wakeb-components": `file:${TARBALL}`, vue: pick("vue"), "@vue/server-renderer": pick("vue"), vite: pick("vite") };
  for (const name of PROVIDER_PEERS[cell.framework]) dependencies[name] = pick(name);
  return { name: `wakeb-peer-fixture-${cell.id}`, private: true, type: "module", dependencies };
}

/** Exact versions recorded in a cell's lockfile for every peer it installs. */
export function lockedVersions(cell) {
  const lock = readJson(join(FIXTURES, cell.id, "package-lock.json"));
  const versions = {};
  for (const name of [...COLUMNS, "@vue/server-renderer"]) {
    const entry = lock.packages[`node_modules/${name}`];
    if (entry) versions[name] = entry.version;
  }
  return versions;
}

const LABELS = {
  en: { provider: "Provider", fixture: "Fixture", result: "Result", range: "Advertised range", min: "minimum", current: "newest in range", pass: "pass", fail: "fail", none: "—", vuetify: "Vuetify", primevue: "PrimeVue", shadcn: "shadcn-vue" },
  ar: { provider: "المزود", fixture: "التثبيت", result: "النتيجة", range: "النطاق المعلن", min: "الحد الأدنى", current: "الأحدث ضمن النطاق", pass: "ناجح", fail: "فاشل", none: "—", vuetify: "Vuetify", primevue: "PrimeVue", shadcn: "shadcn-vue" },
};
const NAMES = { vue: "Vue", vite: "Vite", vuetify: "Vuetify", primevue: "PrimeVue", "@primeuix/themes": "`@primeuix/themes`", "reka-ui": "`reka-ui`" };

export function renderTable(results, lang, pkg = readPackage()) {
  const t = LABELS[lang];
  const rows = [
    `| ${t.provider} | ${t.fixture} | ${COLUMNS.map((name) => NAMES[name]).join(" | ")} | ${t.result} |`,
    `| --- | --- | ${COLUMNS.map(() => "---").join(" | ")} | --- |`,
    `| ${t.none} | ${t.range} | ${COLUMNS.map((name) => `\`${pkg.peerDependencies[name]}\``).join(" | ")} | ${t.none} |`,
  ];
  for (const cell of CELLS) {
    const result = results.cells[cell.id];
    assert(result, `results.json has no ${cell.id} cell`);
    rows.push(`| ${t[cell.framework]} | ${t[cell.tier]} | ${COLUMNS.map((name) => (result.versions[name] ? result.versions[name] : t.none)).join(" | ")} | ${t[result.result]} |`);
  }
  return rows.join("\n");
}

/** Replaces (write) or compares (check) the generated table in both installation guides. */
export function syncDocs(results, write) {
  for (const [lang, path] of Object.entries(DOCS)) {
    const text = readFileSync(path, "utf8");
    const start = text.indexOf(START);
    const end = text.indexOf(END);
    assert(start >= 0 && end > start, `${path} needs the ${START} … ${END} markers`);
    const next = `${text.slice(0, start)}${START}\n\n${renderTable(results, lang)}\n\n${text.slice(end)}`;
    if (write) writeFileSync(path, next);
    else assert.equal(text, next, `${path} peer matrix is stale; run npm run check:peers`);
  }
}

/** Offline consistency check for the docs build: manifests, locks, results and docs agree, every cell passed. */
export function assertMatrixInSync() {
  const pkg = readPackage();
  assert(existsSync(RESULTS), "Run npm run check:peers to create tests/fixtures/peers/results.json");
  const results = readJson(RESULTS);
  assert.deepEqual(Object.keys(results.cells).sort(), CELLS.map((cell) => cell.id).sort(), "results.json cells");
  for (const cell of CELLS) {
    assert.deepEqual(readJson(join(FIXTURES, cell.id, "package.json")), expectedManifest(cell, pkg), `${cell.id} manifest does not match package.json peer ranges; run npm run check:peers -- --update`);
    assert.deepEqual(results.cells[cell.id].versions, lockedVersions(cell), `${cell.id} results were not produced from the committed lockfile; run npm run check:peers`);
    assert.equal(results.cells[cell.id].result, "pass", `${cell.id} peer fixture failed`);
  }
  syncDocs(results, false);
}
